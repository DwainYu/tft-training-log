#!/usr/bin/env node
/**
 * Rebuild the Set 18 static data snapshot from Riot's public data feed.
 *
 * Source
 * ------
 * CommunityDragon (Riot Data Dragon, mirrored), pinned to DDragon 16.19:
 *   https://raw.communitydragon.org/16.19/cdragon/tft/zh_cn.json
 *
 * That DDragon bundle ships the TFT 18.3 patch (released 2026-09-22, see
 * https://teamfighttactics.leagueoflegends.com/en-us/news/game-updates/teamfight-tactics-patch-18-3/).
 * Do not point this script at `latest` — pin the version so a snapshot can
 * be regenerated exactly, then bump the URL + manifest version together.
 *
 * The snapshot in `data/tft/set18/` is generated by this script, not written
 * by hand — regenerate it whenever the patch changes:
 *
 *   node scripts/build-set18-data.mjs        # writes data/tft/set18/*.json
 *
 * What the generator does (all rules documented, no guessing):
 *   - champions: shop units = cost 1-5 that carry at least one trait.
 *     Lux form variants (`DA_18_Lux_*`) are excluded from the base roster
 *     (the base form `DA_Lux18_Base` stays) — 65 base champions.
 *   - traits: the 36 set traits; `breakpoints` = the `minUnits` values of the
 *     published effect tiers.
 *   - items: the set's item pool filtered to real gear (components,
 *     completed, radiant, Ornn/Shimmerscale artifacts, support) with the
 *     category derived from the apiName / tags / composition fields.
 *   - augments: Riot's full set 18 augment pool (592, including carried-over
 *     augments). Emblem entries are flagged `category: "emblem"`.
 *   - descriptions keep their raw template text (`@Gold@` style); the app
 *     does not render them as game text.
 *
 * Locale: names/descriptions are zh-CN (the app's target server). apiNames
 * are locale-independent and serve as the stable ids.
 */

import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE_URL = "https://raw.communitydragon.org/16.19/cdragon/tft/zh_cn.json";
const OUT_DIR = path.resolve(import.meta.dirname, "..", "data", "tft", "set18");

const raw = await (await fetch(SOURCE_URL)).text();
const sha256 = createHash("sha256").update(raw, "utf8").digest("hex");
const data = JSON.parse(raw);

const s18 = data.setData.find((s) => s.number === 18);
if (!s18) throw new Error("Set 18 not found in setData");
const today = new Date().toISOString().slice(0, 10);

/* ------------------------------------------------------------------ */
/* Champions                                                           */
/* ------------------------------------------------------------------ */

// Champion `traits` entries hold the *localized display names* of the traits
// (not apiNames) — resolve them back to trait ids via the trait list.
const traitNameToId = new Map(
  s18.traits.map((t) => [t.name, t.apiName]),
);
const traitIds = new Set([...traitNameToId.values()]);

const isLuxVariant = (apiName) =>
  /^DA_18_Lux_/.test(apiName) || /^DA_Lux18_(?!Base)/.test(apiName);
// 9 trait forms of Lux are excluded; the base form is DA_Lux18_Base.

const champions = s18.champions
  .filter((c) => c.cost >= 1 && c.cost <= 5 && c.traits?.length > 0)
  .filter((c) => !isLuxVariant(c.apiName))
  .map((c) => {
    const traitRefs = c.traits.map((n) => traitNameToId.get(n)).filter((id) => id && traitIds.has(id));
    if (traitRefs.length !== c.traits.length) {
      throw new Error(`${c.apiName}: unresolved trait reference "${c.traits.join(", ")}"`);
    }
    const s = c.stats ?? {};
    const round = (n) => Math.round(n * 10000) / 10000;
    return {
      id: c.apiName,
      name: c.name,
      cost: c.cost,
      traits: traitRefs,
      set: 18,
      ...(c.role ? { role: c.role } : {}),
      stats: {
        hp: s.hp,
        attack: s.damage,
        armor: s.armor,
        magicResist: s.magicResist,
        attackSpeed: round(s.attackSpeed),
        range: s.range,
        critChance: round(s.critChance),
        critMultiplier: round(s.critMultiplier),
        initialMana: s.initialMana,
      },
      ability: c.ability
        ? { name: c.ability.name, description: c.ability.desc }
        : undefined,
      icon: c.icon,
    };
  });

/* ------------------------------------------------------------------ */
/* Traits                                                              */
/* ------------------------------------------------------------------ */

const traits = s18.traits.map((t) => ({
  id: t.apiName,
  name: t.name,
  set: 18,
  breakpoints: (t.effects ?? [])
    .map((e) => e.minUnits)
    .filter((n) => typeof n === "number" && n > 0 && n < 1000),
  description: t.desc ?? "",
  icon: t.icon,
}));

/* ------------------------------------------------------------------ */
/* Items                                                               */
/* ------------------------------------------------------------------ */

const byApiName = Object.fromEntries(Object.values(data.items).map((i) => [i.apiName, i]));
const itemPool = new Set(s18.items);

// Real gear only: drop augments (stored separately), debug/blank placeholders,
// consumables and shop-assist wrappers. Two DA_* families stay: the set's
// emblems (trait items granted by Wisps) and their shop-able component parts.
const isRealGear = (i) =>
  !i.isAugment &&
  !/(Debug|Blank|Unusable|EmptyBag|CypherArmory|TreasureDragonBlankSlot)/.test(i.apiName) &&
  !i.apiName.includes("Consumable") &&
  !i.apiName.startsWith("TFT_Assist") &&
  (!i.apiName.startsWith("DA_") || /^DA_18_Emblem/.test(i.apiName) || /^DA_Component_/.test(i.apiName));

const itemCategory = (i) => {
  if (i.apiName.includes("Emblem")) return "emblem";
  if (i.apiName.startsWith("DA_Component_")) return "component";
  if (i.apiName.includes("Radiant")) return "radiant";
  if (i.apiName.includes("Artifact") || /Ornn|Shimmerscale/.test(i.apiName)) return "artifact";
  if (i.apiName.includes("Support")) return "support";
  if (i.composition.length === 2) return "completed";
  if (i.tags.includes("component")) return "component";
  return "other"; // support-style single items (Zephyr, Moonstone, …) + the Ornn unit entry
};

const items = Object.values(data.items)
  .filter((i) => itemPool.has(i.apiName))
  .filter(isRealGear)
  .filter((i) => i.name != null && i.name !== "" && i.name !== "null")
  .map((i) => ({
    id: i.apiName,
    name: i.name,
    category: itemCategory(i),
    set: 18,
    description: i.desc ?? "",
    ...(i.composition.length ? { composition: i.composition } : {}),
    icon: i.icon,
  }))
  .sort((a, b) => a.name.localeCompare(b.name, "zh-CN") || a.id.localeCompare(b.id));

/* ------------------------------------------------------------------ */
/* Augments                                                            */
/* ------------------------------------------------------------------ */

const augments = s18.augments.map((apiName) => {
  const entry = byApiName[apiName];
  if (!entry) throw new Error(`augment ${apiName} has no definition in data.items`);
  return {
    id: apiName,
    name: entry.name ?? apiName,
    set: 18,
    description: entry.desc ?? "",
    icon: entry.icon,
  };
});

/* ------------------------------------------------------------------ */
/* Write                                                               */
/* ------------------------------------------------------------------ */

const manifest = {
  set: 18,
  name: "Set 18: Enchanted Wilds",
  version: "18.3",
  locale: "zh-CN",
  schemaVersion: 1,
  dataVersion: "s18-18.3-ddragon-16.19",
  source: {
    name: "Riot Data Dragon via CommunityDragon",
    url: SOURCE_URL,
    sha256,
    retrievedAt: today,
    notes: [
      "generated by scripts/build-set18-data.mjs",
      "DDragon bundle 16.19 ships TFT patch 18.3",
      "Lux form variants (DA_18_Lux_*) excluded from the champion base roster",
      "augment tier is not reliably encoded in the source; omitted",
      "descriptions keep raw game-template placeholders (@Gold@ …)",
    ],
  },
  generatedAt: today,
  counts: {
    champions: champions.length,
    traits: traits.length,
    items: items.length,
    augments: augments.length,
  },
};

mkdirSync(OUT_DIR, { recursive: true });
const write = (file, obj) => writeFileSync(path.join(OUT_DIR, file), `${JSON.stringify(obj, null, 2)}\n`);
write("manifest.json", manifest);
write("champions.json", champions);
write("traits.json", traits);
write("items.json", items);
write("augments.json", augments);

console.log("wrote", OUT_DIR);
console.log(manifest.counts);

// sanity: composition references resolve inside the snapshot
const itemIds = new Set(items.map((i) => i.id));
const missing = [...new Set(items.flatMap((i) => i.composition ?? []))].filter((c) => !itemIds.has(c));
if (missing.length) throw new Error(`unresolved item composition refs: ${missing.join(", ")}`);
console.log("composition refs ok");
